const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { afterEach, describe, it } = require('mocha');
const {
  CompletionInstallError,
  installZshCompletion
} = require('../../src/completion/installer');

const homes = [];
afterEach(() => {
  for (const home of homes.splice(0)) {
    fs.rmSync(home, { recursive: true, force: true });
  }
});

function home() {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'fnos-completion-install-'));
  homes.push(directory);
  return directory;
}

function completionTarget(homeDir) {
  return path.join(homeDir, '.fnos', 'completions', '_fnos');
}

function temporaryFiles(directory) {
  return fs.readdirSync(directory).filter((name) => name.endsWith('.tmp'));
}

const content = '#compdef fnos\n# Generated by fnos-cli 0.3.0; DO NOT EDIT.\n_arguments\n';

describe('zsh completion installer', () => {
  it('installs and replaces generated files without touching zshrc', () => {
    const homeDir = home();
    const zshrc = path.join(homeDir, '.zshrc');
    fs.writeFileSync(zshrc, '# user config\n');

    const target = installZshCompletion(content, {
      homeDir,
      randomId: () => 'first'
    });

    assert.equal(target, completionTarget(homeDir));
    assert.equal(fs.readFileSync(target, 'utf8'), content);
    assert.equal(fs.readFileSync(zshrc, 'utf8'), '# user config\n');
    if (process.platform !== 'win32') {
      assert.equal(fs.statSync(path.join(homeDir, '.fnos')).mode & 0o777, 0o700);
      assert.equal(fs.statSync(path.dirname(target)).mode & 0o777, 0o700);
      assert.equal(fs.statSync(target).mode & 0o777, 0o644);
    }

    const updated = content.replace('0.3.0', '0.4.0');
    assert.equal(installZshCompletion(updated, {
      homeDir,
      randomId: () => 'second'
    }), target);
    assert.equal(fs.readFileSync(target, 'utf8'), updated);
  });

  it('returns an absolute target when given a relative home directory', () => {
    const homeDir = home();
    const relativeHomeDir = path.relative(process.cwd(), homeDir);

    const target = installZshCompletion(content, {
      homeDir: relativeHomeDir,
      randomId: () => 'relative-home'
    });

    assert.equal(target, completionTarget(homeDir));
    assert.equal(path.isAbsolute(target), true);
    assert.equal(fs.readFileSync(target, 'utf8'), content);
  });

  it('refuses to overwrite a foreign regular file', () => {
    const homeDir = home();
    const target = completionTarget(homeDir);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, '# user file\n');

    assert.throws(
      () => installZshCompletion(content, { homeDir, randomId: () => 'foreign' }),
      (error) => error instanceof CompletionInstallError && error.exitCode === 4
    );
    assert.equal(fs.readFileSync(target, 'utf8'), '# user file\n');
  });

  it('refuses a symbolic-link target', function () {
    if (process.platform === 'win32') this.skip();
    const homeDir = home();
    const completionDir = path.dirname(completionTarget(homeDir));
    const foreign = path.join(homeDir, 'foreign');
    const target = completionTarget(homeDir);
    fs.mkdirSync(completionDir, { recursive: true });
    fs.writeFileSync(foreign, content);
    fs.symlinkSync(foreign, target);

    assert.throws(
      () => installZshCompletion(content, { homeDir, randomId: () => 'link' }),
      (error) => error instanceof CompletionInstallError && /non-regular/.test(error.message)
    );
    assert.equal(fs.readFileSync(foreign, 'utf8'), content);
  });

  it('refuses a dangling symbolic-link target', function () {
    if (process.platform === 'win32') this.skip();
    const homeDir = home();
    const target = completionTarget(homeDir);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.symlinkSync(path.join(homeDir, 'missing'), target);

    assert.throws(
      () => installZshCompletion(content, { homeDir, randomId: () => 'dangling-link' }),
      (error) => error instanceof CompletionInstallError && /non-regular/.test(error.message)
    );
    assert.equal(fs.lstatSync(target).isSymbolicLink(), true);
  });

  it('refuses a symbolic-link completion directory', function () {
    if (process.platform === 'win32') this.skip();
    const homeDir = home();
    const settingsDir = path.join(homeDir, '.fnos');
    const foreignDirectory = path.join(homeDir, 'foreign-directory');
    fs.mkdirSync(settingsDir);
    fs.mkdirSync(foreignDirectory);
    fs.symlinkSync(foreignDirectory, path.join(settingsDir, 'completions'));

    assert.throws(
      () => installZshCompletion(content, { homeDir, randomId: () => 'dir-link' }),
      (error) => error instanceof CompletionInstallError && /non-directory/.test(error.message)
    );
    assert.deepEqual(fs.readdirSync(foreignDirectory), []);
  });

  it('rejects content without the required two-line generated header', () => {
    const homeDir = home();

    assert.throws(
      () => installZshCompletion('#compdef fnos\n_arguments\n', {
        homeDir,
        randomId: () => 'invalid'
      }),
      (error) => error instanceof CompletionInstallError && error.exitCode === 4
    );
    assert.equal(fs.existsSync(path.join(homeDir, '.fnos')), false);
  });

  it('preserves the old file and removes the temporary file when rename fails', () => {
    const homeDir = home();
    const target = installZshCompletion(content, {
      homeDir,
      randomId: () => 'initial'
    });
    const fsImpl = Object.create(fs);
    fsImpl.renameSync = () => { throw new Error('rename failed'); };

    assert.throws(
      () => installZshCompletion(content.replace('0.3.0', '0.4.0'), {
        homeDir,
        fsImpl,
        randomId: () => 'failed'
      }),
      (error) => error instanceof CompletionInstallError
    );
    assert.equal(fs.readFileSync(target, 'utf8'), content);
    assert.deepEqual(temporaryFiles(path.dirname(target)), []);
  });

  it('removes the temporary file when writing it fails', () => {
    const homeDir = home();
    const fsImpl = Object.create(fs);
    const target = completionTarget(homeDir);
    fsImpl.writeFileSync = (filePath) => {
      throw new Error(`write failed: ${filePath}`);
    };

    assert.throws(
      () => installZshCompletion(content, {
        homeDir,
        fsImpl,
        randomId: () => 'write-failed'
      }),
      (error) => error instanceof CompletionInstallError
    );
    assert.equal(fs.existsSync(target), false);
    assert.deepEqual(temporaryFiles(path.dirname(target)), []);
  });

  it('removes an owned temporary file when writing fails after exclusive creation', () => {
    const homeDir = home();
    const target = installZshCompletion(content, {
      homeDir,
      randomId: () => 'initial'
    });
    const temporary = `${target}.${process.pid}.after-open.tmp`;
    const fsImpl = Object.create(fs);
    fsImpl.writeFileSync = (destination, data, options) => {
      if (typeof destination === 'number') {
        throw new Error(`write failed: ${destination}`);
      }
      const descriptor = fs.openSync(destination, 'wx', options.mode);
      fs.closeSync(descriptor);
      throw new Error(`write failed: ${destination}`);
    };

    assert.throws(
      () => installZshCompletion(content.replace('0.3.0', '0.4.0'), {
        homeDir,
        fsImpl,
        randomId: () => 'after-open'
      }),
      (error) => error instanceof CompletionInstallError
    );
    assert.equal(fs.readFileSync(target, 'utf8'), content);
    assert.equal(fs.existsSync(temporary), false);
  });

  it('preserves an existing temporary file when exclusive creation collides', () => {
    const homeDir = home();
    const target = completionTarget(homeDir);
    const temporary = `${target}.${process.pid}.collision.tmp`;
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(temporary, '# foreign temporary file\n');

    assert.throws(
      () => installZshCompletion(content, {
        homeDir,
        randomId: () => 'collision'
      }),
      (error) => error instanceof CompletionInstallError
    );
    assert.equal(fs.readFileSync(temporary, 'utf8'), '# foreign temporary file\n');
  });
});
